#!/usr/bin/env python3
"""Download and self-host the hand-drawn + readable faces for the PinkSun childlike world.

Why self-host: craft-floor requires a sourced face whose character matches the lettering,
and a phone in a parking lot in February should not wait on fonts.googleapis.com.

Dedupes by content hash: Google serves one variable woff2 for Archivo's whole weight range,
so declaring it three times would ship the same 35 KB file three times.
"""
import hashlib, os, re, ssl, urllib.request

OUT = "/data/pinksun/site/assets/fonts"
os.makedirs(OUT, exist_ok=True)
UA = {"User-Agent": "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/122 Safari/537.36"}
CTX = ssl.create_default_context(); CTX.check_hostname = False; CTX.verify_mode = ssl.CERT_NONE

FAMILIES = [
    ("Gloria+Hallelujah", "Gloria Hallelujah"),
    ("Patrick+Hand", "Patrick Hand"),
    ("Archivo:wght@400;600;700", "Archivo"),
]
KEEP = {"latin"}

def get(url, binary=False):
    req = urllib.request.Request(url, headers=UA)
    with urllib.request.urlopen(req, timeout=40, context=CTX) as r:
        data = r.read()
    return data if binary else data.decode("utf-8", "replace")

entries = []   # (family, md5, weights set, filename, size)
downloaded = {}

for query, local in FAMILIES:
    css = get(f"https://fonts.googleapis.com/css2?family={query}&display=swap")
    for subset, block in re.findall(r"/\*\s*([a-z0-9\-\[\] ]+?)\s*\*/\s*(@font-face\s*\{.*?\})", css, re.S):
        if subset.strip().split()[0] not in KEEP:
            continue
        m = re.search(r"url\((https://[^)]+\.woff2)\)", block)
        if not m:
            continue
        w = re.search(r"font-weight:\s*([\d ]+)", block)
        weight = w.group(1).strip() if w else "400"
        data = downloaded.get(m.group(1)) or get(m.group(1), binary=True)
        downloaded[m.group(1)] = data
        digest = hashlib.md5(data).hexdigest()
        slug = local.lower().replace(" ", "-")
        fname = f"{slug}-{digest[:6]}.woff2"
        path = os.path.join(OUT, fname)
        if not os.path.exists(path):
            open(path, "wb").write(data)
        entries.append({"family": local, "md5": digest, "weight": weight, "file": fname})

# collapse per (family, md5): one @font-face per file, weight range when it serves several
merged = {}
for e in entries:
    key = (e["family"], e["md5"])
    m = merged.setdefault(key, {"weights": [], "file": e["file"]})
    m["weights"].append(e["weight"])

lines = ["/* PinkSun self-hosted faces. Generated by build/fonts.py — do not hand-edit. */", ""]
for (family, _digest), m in merged.items():
    ws = m["weights"]
    weight_decl = ws[0] if len(ws) == 1 else ("100 900" if ws == ["400", "600", "700"] else f"{ws[0]} {ws[-1]}")
    lines.append(
        f"@font-face{{font-family:'{family}';font-style:normal;font-weight:{weight_decl};"
        f"font-display:swap;src:url('fonts/{m['file']}') format('woff2');}}"
    )
open("/data/pinksun/site/assets/fonts.css", "w").write("\n".join(lines) + "\n")

# remove orphaned files
keep = {m["file"] for m in merged.values()}
for f in os.listdir(OUT):
    if f.endswith(".woff2") and f not in keep:
        os.remove(os.path.join(OUT, f))

print("faces declared:")
for (family, _), m in merged.items():
    print(f"  {family:20} weight={m['weights']} -> {m['file']}")
total = sum(os.path.getsize(os.path.join(OUT, f)) for f in os.listdir(OUT))
print("files on disk:", sorted(os.listdir(OUT)))
print("total bytes:", total)
